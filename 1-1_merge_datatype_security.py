import os
import logging
import pandas as pd
import config
import warnings

warnings.simplefilter(action='ignore', category=FutureWarning)

logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s [%(levelname)s] %(message)s",
    datefmt="%Y-%m-%d %H:%M:%S",
    handlers=[
        logging.FileHandler("1-1_merge_datatype_security.log", mode='w', encoding='utf-8'),
        logging.StreamHandler()
    ]
)

START_YEAR = 2015
END_YEAR = 2025
TARGET_DIRECTORY = './raw_data/security_daily_return'
OUTPUT_DIRECTORY = './merge_datatype_csv/security_daily_return'

logging.info("Loading country codes mapping...")
country_codes_df = pd.read_excel('./raw_data/country_code.xlsx')
country_code1_mapping = dict(zip(country_codes_df['Country_name'], country_codes_df['Country_code']))
country_code2_mapping = dict(zip(country_codes_df['Country_name'], country_codes_df['Country_code2']))

sheet_to_variable_mapping = {
    2: 'ri',
    3: 'li',
    4: 'mv',
    5: 'cso',
    6: 'vo'
}

ordered_columns = ['DSCD', 'date', 'year', 'country', 'country_code1', 'country_code2', 'ri', 'li', 'mv', 'vo', 'cso']
os.makedirs(OUTPUT_DIRECTORY, exist_ok=True)

files_by_country = {}
for root_directory, directories, files in os.walk(TARGET_DIRECTORY):
    for file_name in files:
        if file_name.endswith('.xlsm') and not file_name.startswith('~'):
            filename_match = config.FILENAME_PATTERN.match(file_name)
            if not filename_match:
                continue
            
            file_info = filename_match.groupdict()
            file_start_year = int(file_info.get("start_year"))
            file_end_year_str = file_info.get("end_year")
            file_end_year = int(file_end_year_str) if file_end_year_str else file_start_year
            
            if file_end_year < START_YEAR or file_start_year > END_YEAR:
                continue
            
            country = file_info.get("country")

            # Skip files with numeric suffixes (e.g., 'Germany1') if a base folder (e.g., 'Germany') exists, ensuring we use the merged files generated by 1-0_merge_series_for_same_country.py instead.
            base_country = country.rstrip('0123456789')
            if base_country != country and os.path.isdir(os.path.join(TARGET_DIRECTORY, base_country)):
                continue

            company = file_info.get("company")
            country = f"{country}{company}" if company else country

            if country not in files_by_country:
                files_by_country[country] = []
            files_by_country[country].append(os.path.join(root_directory, file_name))

for country, file_paths in files_by_country.items():
    country_df_list = []
    
    for filepath in file_paths:
        logging.info(f"Processing: {filepath}")

        try:
            excel_file = pd.ExcelFile(filepath)
        except Exception as error:
            logging.error(f"Error reading {filepath}: {error}")
            continue

        if len(excel_file.sheet_names) < 6:
            logging.warning(f"Skipping {filepath}, does not have enough worksheets.")
            continue

        merged_file_df = None

        for sheet_index, variable_name in sheet_to_variable_mapping.items():
            sheet_df = pd.read_excel(excel_file, sheet_name=sheet_index, header=1, index_col=0)
            sheet_df.index.name = 'date'

            # Drop empty columns on the right of raw data parsed as 'Unnamed'
            sheet_df = sheet_df.loc[:, ~sheet_df.columns.astype(str).str.startswith('Unnamed')]
            
            for column in sheet_df.columns:
                if pd.notna(column):
                    first_value = str(sheet_df[column].iloc[0])
                    if first_value.startswith("$$ER"):
                        sheet_df[column] = "."

            long_df = sheet_df.reset_index().melt(
                id_vars=['date'], 
                var_name='DSCD', 
                value_name=variable_name
            )
            
            long_df['date'] = pd.to_datetime(long_df['date'], errors='coerce', format='mixed')
            long_df['DSCD'] = long_df['DSCD'].astype(str)

            if merged_file_df is None:
                merged_file_df = long_df
            else:
                merged_file_df = pd.merge(merged_file_df, long_df, on=['date', 'DSCD'], how='outer')

        if merged_file_df is None or merged_file_df.empty:
            continue

        merged_file_df = merged_file_df.dropna(subset=['date'])
        merged_file_df['year'] = merged_file_df['date'].dt.year
        merged_file_df['country'] = country
        lookup_country = country.replace('-', ' ')
        merged_file_df['country_code1'] = country_code1_mapping.get(lookup_country, "")
        merged_file_df['country_code2'] = country_code2_mapping.get(lookup_country, "")

        country_df_list.append(merged_file_df)
        
    if country_df_list:
        final_df = pd.concat(country_df_list, ignore_index=True)
        # Drop overlapping duplicate rows based on company and date, keeping the latest entry
        final_df = final_df.drop_duplicates(subset=['DSCD', 'date'], keep='last')
        final_df = final_df[ordered_columns]
        
        output_filename = os.path.join(OUTPUT_DIRECTORY, f"{country}_sec-ret_{START_YEAR}-{END_YEAR}.csv")
        logging.info(f"Saving output for {country}: {output_filename}")
        final_df.to_csv(output_filename, index=False, encoding='utf-8-sig')
        
        del country_df_list
        del final_df

logging.info("All files saved successfully.")
